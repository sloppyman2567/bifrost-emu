// Thunks.cpp — Bifrost-private host-call syscalls for API thunking:
//   - 0x1000 (GraphicThunk::SYSCALL_NUMBER): guest trampolines trap here;
//     x9 selects the symbol, routed to the graphics, audio or display thunk
//   - 0x100D: Android guest shims resolve an explicit adapter export
//
// Private numbers start at 0x1000, well above the Linux AArch64 syscall
// table, so they never collide with real syscalls.
#include "System/Core/Emulator.hpp"
#include "System/Memory/Memory.hpp"
#include "System/Core/CPU.hpp"
#include "System/Syscalls/Syscalls.hpp"
#include "System/Graphics/Display/Graphics.hpp"
#include "System/Graphics/Thunks/GraphicThunk.hpp"
#include "System/Graphics/Thunks/DisplayThunk.hpp"
#include "System/Audio/AudioThunk.hpp"
#include <cerrno>
#include <string>
namespace arm64emu {
int64_t syscall_host_thunks(Emulator& emu, CPU& cpu, uint64_t num) {
    switch (num) {
        // ── Bifrost-emu internal thunk syscall ────────────
        // Trampolines generated by GraphicThunk use this syscall number
        // to trap into the host. x9 holds the symbol_id; the thunk looks
        // up the host function, reads args from x0..x7, calls it, and
        // writes the return value to x0.
        //
        // The number (0x1000 = 4096) is high enough to never collide
        // with real Linux AArch64 syscalls (which go up to ~451 as of
        // kernel 6.x). When thunking is disabled, this case is unreachable (no
        // trampolines are ever written to guest memory).
        case GraphicThunk::SYSCALL_NUMBER: {
            // the thunk syscall is shared by GraphicThunk,
            // AudioThunk, and DisplayThunk. Each has its own per-thunk
            // symbol_id namespace starting from 0, so we try each in
            // order until one accepts the symbol_id.
            //
            // We try GraphicThunk first because most guests use it; if
            // it returns -ENOENT (symbol_id out of range), we fall
            // through to AudioThunk, then DisplayThunk.
            uint32_t sym_id = static_cast<uint32_t>(cpu.regs[9]);
            auto* gthunk = emu.graphics().thunk();
            if (gthunk && gthunk->enabled()) {
                int64_t r = gthunk->dispatch(cpu, sym_id);
                if (r == 0) return 0;            // handled
                if (r != -ENOENT) {               // real error from GraphicThunk
                    ret_host(r);
                    return 0;
                }
            }
            // Try AudioThunk.
            auto* athunk = emu.graphics().audio_thunk();
            if (athunk && athunk->enabled()) {
                int64_t r = athunk->dispatch(cpu, sym_id);
                // AudioThunk arms return the REAL guest x0 value (0 is a
                // legitimate success there — e.g. snd_pcm_open). Only
                // -ENOENT means "not my symbol".
                if (r != -ENOENT) {
                    ret_host(r);
                    return 0;
                }
            }
            // Try DisplayThunk.
            auto* dthunk = emu.graphics().display_thunk();
            if (dthunk && dthunk->enabled()) {
                int64_t r = dthunk->dispatch(cpu, sym_id);
                if (r == 0) return 0;
                if (r != -ENOENT) {
                    ret_host(r);
                    return 0;
                }
            }
            // None of the thunks recognized the symbol_id.
            ret_err(ENOSYS);
            return 0;
        }
        case 0x100D: { // Android guest shim: resolve an explicit adapter export.
            if (!emu.android_runtime()) { ret_host(-EPERM); return 0; }
            auto string_arg = [&](uint64_t address) {
                std::string value;
                for (size_t i = 0; i < 128; ++i) {
                    char c = static_cast<char>(emu.mem().load<uint8_t>(address + i));
                    if (!c) return value;
                    value.push_back(c);
                }
                throw EmuError("oversized Android shim symbol");
            };
            try {
                auto library = string_arg(cpu.regs[0]);
                auto symbol = string_arg(cpu.regs[1]);
                uint64_t address = 0;
                if (library == "libEGL.so" || library == "libGLESv2.so") {
                    if (auto* thunk = emu.graphics().thunk(); thunk && thunk->enabled()) {
                        address = thunk->resolve(library, symbol);
                        if (!address && library == "libGLESv2.so" && symbol == "glReadPixels")
                            address = thunk->resolve("libGL.so.1", symbol);
                    }
                } else if (library == "libandroid.so" || library == "liblog.so") {
                    if (auto* thunk = emu.graphics().display_thunk(); thunk && thunk->enabled())
                        address = thunk->resolve(library, symbol);
                } else if (library == "libaaudio.so") {
                    if (auto* thunk = emu.graphics().audio_thunk(); thunk && thunk->enabled())
                        address = thunk->resolve(library, symbol);
                }
                cpu.regs[0] = address;
            } catch (const EmuError&) { ret_host(-EFAULT); }
            return 0;
        }
        default:
            return SYSCALL_NOT_HANDLED;
    }
    return 0;
}
} // namespace arm64emu
