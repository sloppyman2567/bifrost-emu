struct Allocate { uint64_t size, offset, physical; };
struct Ping { uint64_t offset, size, metadata; uint32_t resource, wait_fd, wait_flags, direction; };
constexpr uint32_t ALLOCATE = _IOWR('G', 10, Allocate);
constexpr uint32_t PING = _IOWR('G', 12, Ping);
constexpr uint64_t SLOT = 1 << 20, INPUT = 512, OUTPUT = 0x10000, RESULT = 256;
constexpr uint64_t ARGUMENT = 0x8000;
enum { INIT = 0, DECODE = 2, IMAGE = 3 };

struct Device {
    Memory memory{false};
    std::unique_ptr<Node> node;
    uint8_t* arena = nullptr;
    int ping(unsigned codec, unsigned slot, unsigned op) {
        Ping ping{};
        ping.metadata = uint64_t(codec) << 56 | uint64_t(slot) << 8 | op;
        memory.store(ARGUMENT, ping);
        return node->ioctl(PING, ARGUMENT, memory);
    }
    void param(unsigned slot, unsigned index, uint64_t value) {
        std::memcpy(arena + slot * SLOT + index * 8, &value, 8);
    }
    template<class T> T result(unsigned slot, unsigned offset) {
        T value; std::memcpy(&value, arena + slot * SLOT + RESULT + offset, sizeof(value)); return value;
    }
};

// The guest passes stale output dimensions; the host must ignore them.
static int image(Device& device, unsigned codec, unsigned slot, uint64_t opaque, const AVFrame* reference) {
    device.param(slot, 0, 1);
    device.param(slot, 1, 320); device.param(slot, 2, 240);
    device.param(slot, 3, 320); device.param(slot, 4, 240);
    device.param(slot, 5, 1); device.param(slot, 6, UINT64_MAX);
    device.param(slot, 7, OUTPUT);
    CHECK(device.ping(codec, slot, IMAGE) == 0);
    CHECK(device.result<int32_t>(slot, 0) == 0);
    CHECK(device.result<uint32_t>(slot, 8) == 0x102);
    const unsigned width = device.result<uint32_t>(slot, 16), height = device.result<uint32_t>(slot, 24);
    CHECK(width == unsigned(reference->width) && height == unsigned(reference->height));
    CHECK(device.result<uint64_t>(slot, 32) == opaque);
    const uint8_t* out = device.arena + slot * SLOT + OUTPUT;
    for (unsigned plane : {0u, 2u, 1u}) {
        const unsigned w = plane ? width / 2 : width, h = plane ? height / 2 : height;
        for (unsigned row = 0; row < h; ++row, out += w)
            CHECK(!std::memcmp(out, reference->data[plane] + row * reference->linesize[plane], w));
    }
    return 0;
}

static int stream(Device& device, unsigned codec, unsigned slot, AVCodecID id,
                  const uint8_t* const* packets, const size_t* sizes) {
    device.param(slot, 0, 1); device.param(slot, 1, 100);
    CHECK(device.ping(codec, slot, INIT) == 0);
    const AVCodec* implementation = avcodec_find_decoder(id);
    CHECK(implementation);
    AVCodecContext* context = avcodec_alloc_context3(implementation);
    CHECK(context);
    context->thread_count = 1;
    CHECK(avcodec_open2(context, implementation, nullptr) == 0);
    AVPacket* packet = av_packet_alloc();
    AVFrame* frame = av_frame_alloc();
    int failed = 0;
    for (unsigned i = 0; i < 2 && !failed; ++i) {
        // Opaque guest work addresses: equal values must not be dereferenced.
        const uint64_t opaque = 0x7f0000001000ull + i * 0x40;
        std::memcpy(device.arena + slot * SLOT + INPUT, packets[i], sizes[i]);
        device.param(slot, 0, 1); device.param(slot, 1, INPUT);
        device.param(slot, 2, sizes[i]); device.param(slot, 3, opaque);
        if (device.ping(codec, slot, DECODE) || device.result<int32_t>(slot, 0)) { failed = 1; break; }
        av_packet_unref(packet);
        packet->data = const_cast<uint8_t*>(packets[i]); packet->size = int(sizes[i]);
        if (avcodec_send_packet(context, packet) || avcodec_receive_frame(context, frame)) { failed = 1; break; }
        packet->data = nullptr; packet->size = 0;
        failed = image(device, codec, slot, opaque, frame);
        // Exactly one image per shown frame.
        device.param(slot, 0, 1);
        if (!failed && (device.ping(codec, slot, IMAGE) || device.result<int32_t>(slot, 0) == 0)) failed = 1;
    }
    av_frame_free(&frame); av_packet_free(&packet); avcodec_free_context(&context);
    CHECK(!failed);
    return 0;
}

int main() {
    Device device;
    int error = 0;
    device.node = open_goldfish_media(O_RDWR, &error);
    CHECK(device.node && !error);
    CHECK(device.memory.map_range(ARGUMENT, 4096));
    Allocate block{2 * SLOT, 0, 0};
    device.memory.store(ARGUMENT, block);
    CHECK(device.node->ioctl(ALLOCATE, ARGUMENT, device.memory) == 0);
    void* mapped = ::mmap(nullptr, 2 * SLOT, PROT_READ | PROT_WRITE, MAP_SHARED, device.node->host_fd(), 0);
    CHECK(mapped != MAP_FAILED);
    device.arena = static_cast<uint8_t*>(mapped);
    CHECK(device.ping(0, 0, 1) == 0); // media transport handshake
    // Both guest VPX modules allocate their own context ID 1.
    const uint8_t* vp8[] = {vp8_0, vp8_1}; const size_t vp8_sizes[] = {sizeof vp8_0, sizeof vp8_1};
    const uint8_t* vp9[] = {vp9_0, vp9_1}; const size_t vp9_sizes[] = {sizeof vp9_0, sizeof vp9_1};
    CHECK(stream(device, 0, 0, AV_CODEC_ID_VP8, vp8, vp8_sizes) == 0);
    CHECK(stream(device, 1, 1, AV_CODEC_ID_VP9, vp9, vp9_sizes) == 0);
    ::munmap(mapped, 2 * SLOT);
    printf("android_goldfish_media: %d checks passed\n", checks);
    return 0;
}
