def shim(library, names, hidden=(), resolver=None):
    """Assembly for lazy thunk exports; `library` names the thunk table.
    Names in `hidden` get the local-only label thunk_<name>, for C wrappers.
    With `resolver`, each export instead calls that C function with its name
    and jumps to the returned guest address."""
    if resolver:
        resolve = ["adrp x0,.Lname_{name}", "add x0,x0,:lo12:.Lname_{name}", f"bl {resolver}"]
    else:
        resolve = ["adrp x0,.Llibrary", "add x0,x0,:lo12:.Llibrary", "adrp x1,.Lname_{name}",
                   "add x1,x1,:lo12:.Lname_{name}", "mov x8,#0x100d", "svc #0"]
    lines = [".text"]
    for name in sorted(set(names)):
        label = "thunk_" + name if name in hidden else name
        # Lazy atomic cache per export. Preserve every AAPCS64 argument, including
        # SIMD and variadic arguments, before resolving the existing shared thunk.
        lines += [
            f".global {label}",
            *([f".hidden {label}"] if name in hidden else []),
            f".type {label},%function",
            f"{label}:",
            f"adrp x16,.Lptr_{name}",
            f"add x16,x16,:lo12:.Lptr_{name}",
            "ldar x17,[x16]",
            f"cbnz x17,.Lcall_{name}",
            "sub sp,sp,#208",
            "stp x0,x1,[sp,#0]",
            "stp x2,x3,[sp,#16]",
            "stp x4,x5,[sp,#32]",
            "stp x6,x7,[sp,#48]",
            "stp x8,x30,[sp,#64]",
            "stp q0,q1,[sp,#80]",
            "stp q2,q3,[sp,#112]",
            "stp q4,q5,[sp,#144]",
            "stp q6,q7,[sp,#176]",
            *[line.format(name=name) for line in resolve],
            "cmp x0,#0",
            f"b.le .Lmissing_{name}",
            "mov x17,x0",
            f"adrp x16,.Lptr_{name}",
            f"add x16,x16,:lo12:.Lptr_{name}",
            "stlr x17,[x16]",
            "ldp x0,x1,[sp,#0]",
            "ldp x2,x3,[sp,#16]",
            "ldp x4,x5,[sp,#32]",
            "ldp x6,x7,[sp,#48]",
            "ldp x8,x30,[sp,#64]",
            "ldp q0,q1,[sp,#80]",
            "ldp q2,q3,[sp,#112]",
            "ldp q4,q5,[sp,#144]",
            "ldp q6,q7,[sp,#176]",
            "add sp,sp,#208",
            f".Lcall_{name}:",
            "br x17",
            f".Lmissing_{name}:",
            "mov x0,#2",
            f"adrp x1,.Lerror_{name}",
            f"add x1,x1,:lo12:.Lerror_{name}",
            f"mov x2,#.Lerror_end_{name}-.Lerror_{name}",
            "mov x8,#64",
            "svc #0",
            "mov x0,#126",
            "mov x8,#94",
            "svc #0",
            "brk #1",
            f".size {label},.-{label}",
        ]
    lines += [".section .rodata", f'.Llibrary: .asciz "{library}"']
    for name in sorted(set(names)):
        lines += [
            f'.Lname_{name}: .asciz "{name}"',
            f'.Lerror_{name}: .ascii "Android adapter: missing {library}:{name}\\n"',
            f".Lerror_end_{name}:",
        ]
    lines += [".bss", ".balign 8"]
    for name in sorted(set(names)):
        lines += [f".Lptr_{name}: .quad 0"]
    lines += ['.section .note.GNU-stack,"",%progbits']
    return "\n".join(lines) + "\n"


def gles1_commands():
    """OpenGL ES 1.x common-profile commands from the vendored Khronos registry."""
    import xml.etree.ElementTree as ElementTree
    registry = ElementTree.parse(ROOT / "ThirdParty/GLRegistry/gl.xml").getroot()
    return {command.get("name")
            for feature in registry.iter("feature") if feature.get("api") == "gles1"
            for require in feature.iter("require") if require.get("profile") in (None, "common")
            for command in require.iter("command")}


def gles1_fixed_function_stubs(names):
    """C source of one stub per OpenGL ES 1.x command that has no ES 2 equivalent. Every one of them returns void
    (checked against the registry when this was written), so a stub takes no parameters and ignores its arguments."""
    lines = ["// Generated by build-android-adapters.py from the gles1 feature of the Khronos registry.",
             "extern void bifrost_gles1_unsupported(const char *);"]
    lines += [f'__attribute__((visibility("default"))) void {name}(void) {{ bifrost_gles1_unsupported("{name}"); }}'
              for name in sorted(names)]
    return "\n".join(lines) + "\n"


def platform_forwards(staging, thunked):
    """Public LIBANDROID exports the managed libandroid forwards to the image's
    real library. A linked public-library namespace exposes only libandroid.so
    itself, not its re_android.so dependency, so an app library importing
    e.g. AAsset_seek needs its own export here. Window-handle functions keep
    their thunked/wrapped behaviour: the real ones would receive host handles."""
    map_file = "libandroid.map.txt"
    extract("libandroid", staging / "libandroid", {map_file})
    text = (staging / "libandroid" / map_file).read_text()
    block = re.search(r"^LIBANDROID \{\s*global:(.*?)^\s*local:", text, re.MULTILINE | re.DOTALL)
    public = re.findall(r"^\s*(\w+);", block.group(1), re.MULTILINE)
    adapters = ROOT / "Guest/Android/Adapters"
    provided = set(thunked)
    provided.update(re.findall(r"^[\w ]+[ *](A\w+)\(", (adapters / "surface.c").read_text(), re.MULTILINE))
    provided.update(re.findall(r"^PLATFORM\w*\([^,]+,\s*(\w+)",
                               (adapters / "managed_looper.c").read_text(), re.MULTILINE))
    window = {n for n in public if n.startswith("ANativeWindow_") or n == "ASurfaceControl_createFromWindow"}
    return sorted(n for n in public if n not in provided and n not in window)


VULKAN_DISPATCHABLE = {"VkInstance", "VkPhysicalDevice", "VkDevice", "VkQueue",
                       "VkCommandBuffer"}


def vulkan_commands():
    """(first parameter type, alias target) per command, from the vendored
    Khronos vk.xml.

    The alias map matters: Android's loader asks a driver for the KHR names
    (`vkGetPhysicalDeviceFeatures2KHR` and friends), but the host Linux loader
    exports only the core names they alias. Resolving an alias by its own name
    finds nothing, so those commands have to be reached through their target.
    """
    import xml.etree.ElementTree as ElementTree
    registry = ElementTree.parse(
        ROOT / "ThirdParty/VulkanHeaders/registry/vk.xml").getroot()
    first, aliases = {}, {}
    for command in registry.find("commands").iter("command"):
        # Only alias-only rows carry the name on the element; every other
        # command names itself in <proto>.
        name = command.get("name")
        if name:
            aliases[name] = command.get("alias")
            continue
        proto = command.find("proto")
        if proto is None:
            continue
        params = [param for param in command.findall("param")
                  if param.get("api") is None
                  or "vulkan" in [a.strip() for a in param.get("api").split(",")]]
        first[proto.findtext("name")] = (params[0].findtext("type")
                                         if params else None)
    resolved = {}
    for name, target in aliases.items():
        if target in first:
            first[name] = first[target]
            resolved[name] = target
    return first, resolved


def vulkan_allocator_arguments():
    """Command -> argument index of its VkAllocationCallbacks pointer.

    A driver calls pfnAllocation/pfnFree while it runs, but an app's callbacks
    are guest function pointers: passing them through makes the host driver
    jump into guest memory and fault (vkCreatePipelineCache, 2026-11-06, host
    fault with pc == addr). The shim zeroes that argument so the host uses its
    own allocator, which is also what an ICD without a host allocator bridge
    must do.
    """
    import xml.etree.ElementTree as ElementTree
    registry = ElementTree.parse(
        ROOT / "ThirdParty/VulkanHeaders/registry/vk.xml").getroot()
    found = {}
    for command in registry.find("commands").iter("command"):
        # vk.xml names a command inside <proto>, not on the element.
        name = (command.findtext("proto/name") or "").strip()
        if not name:
            continue
        params = [param for param in command.findall("param")
                  if param.get("api") is None
                  or "vulkan" in [a.strip() for a in param.get("api").split(",")]]
        for index, param in enumerate(params):
            if "VkAllocationCallbacks" in ElementTree.tostring(
                    param, encoding="unicode"):
                found[name] = index
                break
    return found


def vulkan_shims():
    """Assembly for one entry point per Vulkan command.

    Android's libvulkan loader hands a driver back the dispatchable objects it
    created and expects the driver to call through them, so a command's first
    argument is one of this module's two-word objects: the loader's dispatch
    slot, then the host handle. The shim resolves the host loader symbol lazily
    (0x100D, like the other adapters) and replaces that object with the host
    handle before jumping to it. Written in assembly so no signature — SIMD,
    variadic or stack arguments — has to be spelled out. The table at the end
    lets the module hand these addresses out by command name.
    """
    commands, aliases = vulkan_commands()
    allocators = vulkan_allocator_arguments()
    # The name the host loader must be asked for: an alias' target, else itself.
    host_names = {name: aliases.get(name, name) for name in commands}
    save = [
        "sub sp,sp,#208",
        "stp x0,x1,[sp,#0]",
        "stp x2,x3,[sp,#16]",
        "stp x4,x5,[sp,#32]",
        "stp x6,x7,[sp,#48]",
        "stp x8,x30,[sp,#64]",
        "stp q0,q1,[sp,#80]",
        "stp q2,q3,[sp,#112]",
        "stp q4,q5,[sp,#144]",
        "stp q6,q7,[sp,#176]",
    ]
    restore = [
        "ldp x0,x1,[sp,#0]",
        "ldp x2,x3,[sp,#16]",
        "ldp x4,x5,[sp,#32]",
        "ldp x6,x7,[sp,#48]",
        "ldp x8,x30,[sp,#64]",
        "ldp q0,q1,[sp,#80]",
        "ldp q2,q3,[sp,#112]",
        "ldp q4,q5,[sp,#144]",
        "ldp q6,q7,[sp,#176]",
        "add sp,sp,#208",
    ]
    lines = [".text"]
    for name in sorted(commands):
        lines += [
            f".type bf_vk_{name},%function",
            f"bf_vk_{name}:",
            f"adrp x16,.Lvptr_{name}",
            f"add x16,x16,:lo12:.Lvptr_{name}",
            "ldar x17,[x16]",
            f"cbnz x17,.Lvcall_{name}",
            *save,
            "adrp x0,.Lvlib",
            "add x0,x0,:lo12:.Lvlib",
            f"adrp x1,.Lvhost_{name}",
            f"add x1,x1,:lo12:.Lvhost_{name}",
            "mov x8,#0x100d",
            "svc #0",
            "cmp x0,#0",
            f"b.le .Lvmissing_{name}",
            "mov x17,x0",
            f"adrp x16,.Lvptr_{name}",
            f"add x16,x16,:lo12:.Lvptr_{name}",
            "stlr x17,[x16]",
            *restore,
            f".Lvcall_{name}:",
            # Word 1 of the object is the host handle (see
            # Guest/Android/Include/vulkan_dispatchable.h). A null dispatchable
            # is legal for vkGetInstanceProcAddr/vkGetDeviceProcAddr, so the
            # load has to be skipped rather than fault.
            *(["cbz x0,.Lvnull_" + name, "ldr x0,[x0,#8]", f".Lvnull_{name}:"]
              if commands[name] in VULKAN_DISPATCHABLE else []),
            # Guest allocation callbacks must not reach the host driver: it
            # would call guest code from host context and fault.
            *([f"mov x{allocators[name]},xzr"]
              if name in allocators and allocators[name] < 8 else []),
            "br x17",
            f".Lvmissing_{name}:",
            "add sp,sp,#208",
            f"adrp x0,.Lvname_{name}",
            f"add x0,x0,:lo12:.Lvname_{name}",
            "b bf_vk_missing",
            f".size bf_vk_{name},.-bf_vk_{name}",
        ]
    lines += [".section .rodata", '.Lvlib: .asciz "libvulkan.so"']
    for name in sorted(commands):
        lines += [f'.Lvname_{name}: .asciz "{name}"',
                  f'.Lvhost_{name}: .asciz "{host_names[name]}"']
    lines += [".bss", ".balign 8"]
    for name in sorted(commands):
        lines += [f".Lvptr_{name}: .quad 0"]
    lines += ['.section .data.rel.ro,"aw",%progbits', ".balign 8",
              ".hidden bf_vk_shims", ".global bf_vk_shims", "bf_vk_shims:"]
    for name in sorted(commands):
        lines += [f".quad .Lvname_{name}", f".quad .Lvhost_{name}",
                  f".quad bf_vk_{name}"]
    lines += [".quad 0", ".quad 0", ".quad 0",
              '.section .note.GNU-stack,"",%progbits']
    return "\n".join(lines) + "\n"


def vulkan_extension_table():
    """C source mapping each device extension to the commands it adds.

    A driver that advertises an extension owes the app every command in it.
    Where the host loader has no symbol for one of them the module refuses the
    command, the loader leaves that dispatch slot NULL, and an app that
    enabled the extension calls it (Unity 2.x + VK_KHR_fragment_shading_rate,
    2026-11-06). The module checks this table before it forwards the host's
    device extension list, so advertisement and entry points agree.
    """
    import xml.etree.ElementTree as ElementTree
    registry = ElementTree.parse(
        ROOT / "ThirdParty/VulkanHeaders/registry/vk.xml").getroot()
    extensions = []
    for extension in registry.find("extensions").iter("extension"):
        if extension.get("type") != "device":
            continue
        commands = []
        for require in extension.findall("require"):
            for command in require.findall("command"):
                name = command.get("name")
                if name and name not in commands:
                    commands.append(name)
        if commands:
            extensions.append((extension.get("name"), commands))
    extensions.sort()
    lines = [
        "/* Generated from vk.xml by build-android-adapters.py: the commands each",
        "   device extension adds, for bf_vk_extension_servable(). */",
        '#include "vulkan_dispatchable.h"',
        "",
    ]
    for index, (_, commands) in enumerate(extensions):
        joined = ", ".join('"' + command + '"' for command in commands)
        lines.append(f"static const char *const bf_ext_{index}[] = {{{joined}, 0}};")
    lines += ["", "const struct bf_vk_extension bf_vk_extensions[] = {"]
    for index, (name, commands) in enumerate(extensions):
        lines.append(f'    {{"{name}", bf_ext_{index}, {len(commands)}}},')
    lines += ["    {0, 0, 0},", "};", ""]
    return "\n".join(lines)


def build(runtime, output):
    spec = importlib.util.spec_from_file_location(
        "runtime", ROOT / "Tools/Android/fetch-android-runtime.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.install(runtime)
    bionic = runtime / "apex/com.android.runtime/lib64/bionic"
    common = [
        "clang",
        "--target=aarch64-linux-android35",
        "-fuse-ld=lld",
        "-nostdlib",
        "-ffreestanding",
        "-O2",
        "-Wall",
        "-Wextra",
        "-I" + str(ROOT / "Guest/Android/Include"),
        "-I" + str(ROOT / "Include"),
        "-Wl,-z,max-page-size=16384",
        "-Wl,-z,defs",
    ]
    groups = {
        name: [] for name in ["libandroid.so", "liblog.so", "libEGL.so", "libGLESv2.so"]
    }
    for line in (ROOT / "Tools/CodeGen/thunk_dp.txt").read_text().splitlines():
        fields = line.split()
        if len(fields) < 6 or fields[0].startswith("#"):
            continue
        name, group = fields[:2]
        library = {
            "ANDROID": (
                "liblog.so" if name.startswith("__android_log_") else "libandroid.so"
            ),
            "EGL": "libEGL.so",
            "GLES": "libGLESv2.so",
        }.get(group)
        if library:
            groups[library].append(name)
    # Core GL readback uses the same ABI in GLES. The Android shim resolver
    # routes it to the existing GL readback/marshalling implementation.
    groups["libGLESv2.so"].append("glReadPixels")
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix=".android-adapters-", dir=output.parent
    ) as work:
        staging = Path(work)
        common += prepare_headers(staging / "headers")
        dependencies = build_zlib(staging, bionic, common)
        for library, names in groups.items():
            if library == "liblog.so":
                names = ["__android_log_write"]
            assembly = staging / (library + ".S")
            assembly.write_text(shim(library, names))
            inputs = [str(assembly)]
            if library == "libandroid.so":
                inputs += [
                    str(ROOT / "Guest/Android/Adapters/assets.c"),
                    str(bionic / "libc.so"),
                ]
            if library == "liblog.so":
                inputs += [str(ROOT / "Guest/Android/Adapters/log.c"), str(bionic / "libc.so")]
            subprocess.run(
                common
                + ["-fPIC", "-shared", "-Wl,-soname," + library]
                + inputs
                + ["-o", str(staging / library)],
                check=True,
            )
        subprocess.run(
            common
            + [
                "-fPIE",
                "-pie",
                "-Wl,--dynamic-linker=/system/bin/linker64",
                "-Wl,-rpath,/system/lib64:/apex/com.android.runtime/lib64/bionic",
                str(ROOT / "Tests/Unit/android_bionic_start.S"),
                str(ROOT / "Guest/Android/Launchers/native_launcher.c"),
                str(staging / "libandroid.so"),
                str(bionic / "libc.so"),
                str(bionic / "libdl.so"),
                str(bionic / "libdl_android.so"),
                "-Wl,--allow-shlib-undefined",
                "-o",
                str(staging / "bifrost-native"),
            ],
            check=True,
        )
        # ManagedLauncher and ActivityProbe share the window/identity JNI bridge.
        subprocess.run(common + ["-std=c2x", "-mno-outline-atomics", "-fPIC", "-shared", "-Wl,-soname,libbifrost-activity.so",
                                 str(ROOT / "Guest/Android/Adapters/activity_window.c"),
                                 str(ROOT / "Guest/Android/Adapters/gralloc_probe.c"),
                                 str(ROOT / "Guest/Android/Adapters/surface_buffers.c"),
                                 str(ROOT / "Guest/Android/Adapters/audio_track.c"),
                                 str(staging / "libandroid.so"), str(bionic / "libc.so"),
                                 str(bionic / "libdl.so"), str(bionic / "libdl_android.so"),
                                 "-o", str(staging / "libbifrost-activity.so")], check=True)
        names = list(groups) + ["bifrost-native", "libbifrost-activity.so", "libz.so",
                                "libz.so.LICENSE"]
        # Managed apps run inside the image's real framework, whose libraries
        # import Android-private EGL/GLES/libandroid symbols. Each managed
        # adapter keeps its thunked exports first in Bionic's breadth-first
        # lookup and depends on the real library, which the runner installs
        # under the same-length soname re_<name> (lib -> re_).
        managed = staging / "managed"
        managed.mkdir()
        subprocess.run(common + ["-std=c2x", "-mno-outline-atomics", "-fPIC", "-shared", "-Wl,-soname,mapper.bifrost.so",
                                 str(ROOT / "Guest/Android/Adapters/gralloc_mapper.c"),
                                 str(bionic / "libc.so"), "-o", str(managed / "mapper.bifrost.so")],
                       check=True)
        names.append("managed/mapper.bifrost.so")
        # Android's Vulkan loader opens this as its driver HAL module
        # (hw_get_module "vulkan" -> /vendor/lib64/hw/vulkan.<name>.so). It owns
        # no Vulkan state: every entry point forwards to the host loader
        # through DisplayThunk, and it filters the loader-provided Android
        # surface extension the host does not know. The dispatchable objects the
        # loader expects to own are the module's own guest structs (see its
        # vulkan_dispatchable.h); the generated shims unwrap them per command.
        vulkan_shim_source = staging / "vulkan-shims.S"
        vulkan_shim_source.write_text(vulkan_shims())
        vulkan_extension_source = staging / "vulkan-extensions.c"
        vulkan_extension_source.write_text(vulkan_extension_table())
        subprocess.run(common + ["-std=c2x", "-mno-outline-atomics", "-fPIC", "-shared",
                                 "-Wl,-soname,vulkan.bifrost.so",
                                 "-I" + str(ROOT / "ThirdParty/VulkanHeaders/include"),
                                 str(ROOT / "Guest/Android/Adapters/vulkan_hal.c"),
                                 str(ROOT / "Guest/Android/Adapters/vulkan_dispatchable.c"),
                                 str(ROOT / "Guest/Android/Adapters/vulkan_handles.c"),
                                 str(ROOT / "Guest/Android/Adapters/vulkan_native_buffer.c"),
                                 str(vulkan_extension_source),
                                 str(vulkan_shim_source),
                                 str(bionic / "libc.so"),
                                 "-o", str(managed / "vulkan.bifrost.so")], check=True)
        names.append("managed/vulkan.bifrost.so")
        # Preloaded into app processes: see its header.
        subprocess.run(common + ["-std=c2x", "-mno-outline-atomics", "-fPIC", "-shared",
                                 "-Wl,-soname,libbifrost-binder-attach.so", "-Wl,--no-as-needed",
                                 str(ROOT / "Guest/Android/Adapters/binder_attach.c"),
                                 str(bionic / "libc.so"), str(bionic / "libdl.so"),
                                 "-o", str(managed / "libbifrost-binder-attach.so")], check=True)
        names.append("managed/libbifrost-binder-attach.so")
        subprocess.run(common + ["-fPIE", "-pie", "-Wl,--dynamic-linker=/system/bin/linker64",
                                 str(ROOT / "Tests/Unit/android_bionic_start.S"),
                                 str(ROOT / "Guest/Android/Launchers/am.c"), str(bionic / "libc.so"),
                                 "-Wl,--allow-shlib-undefined", "-o", str(staging / "managed/am")], check=True)
        names.append("managed/am")
        thunked_android = [n for n in groups["libandroid.so"]
                           if not n.startswith(("AConfiguration_", "ALooper_", "AChoreographer_"))]
        # Managed Java MessageQueue polls the image's libutils Looper. Native
        # consumers (including Chromium's MessagePumpAndroid) must register
        # their event/timer fds with that SAME looper via re_android.so. A host
        # thunk looper here silently strands native work while Java keeps polling.
        # Share the AudioThunk export registry. Managed AAudio streams must
        # stay on the host backend, rather than fall back to Android AudioTrack.
        aa_exports = re.findall(r"REG\(aa_libs,\s*(\w+)\)",
                               (ROOT / "Source/System/Audio/AudioThunk/AudioThunk.cpp").read_text())
        # aaudio.c runs data callbacks on its own Bionic thread, like libaaudio;
        # it wraps open/close and drives the private bifrost_aaudio_* calls.
        aa_hidden = {"AAudioStreamBuilder_openStream", "AAudioStream_close"}
        aa_hidden.update(n for n in aa_exports if n.startswith("bifrost_"))
        assembly = staging / "managed-libaaudio.so.S"
        assembly.write_text(shim("libaaudio.so", aa_exports, aa_hidden))
        subprocess.run(common + ["-fPIC", "-shared", "-Wl,-soname,libaaudio.so",
                                 str(assembly), str(ROOT / "Guest/Android/Adapters/aaudio.c"),
                                 str(bionic / "libc.so"), "-o", str(managed / "libaaudio.so")],
                       check=True)
        names.append("managed/libaaudio.so")
        # OpenSL ES players render through the managed libaaudio above, whose
        # callback thread runs their buffer-queue callbacks. The image's real
        # libOpenSLES plays through AudioFlinger, which is not provided.
        subprocess.run(common + ["-std=c2x", "-fPIC", "-shared", "-Wl,-soname,libOpenSLES.so",
                                 str(ROOT / "Guest/Android/Adapters/opensles.c"),
                                 str(managed / "libaaudio.so"), str(bionic / "libm.so"),
                                 str(bionic / "libc.so"), "-o", str(managed / "libOpenSLES.so")],
                       check=True)
        names.append("managed/libOpenSLES.so")
        for soname, table, exports in (
            ("libandroid.so", "libandroid.so", thunked_android),
            ("libEGL.so", "libEGL.so", groups["libEGL.so"]),
            ("libGLESv2.so", "libGLESv2.so", groups["libGLESv2.so"]),
            ("libGLESv3.so", "libGLESv2.so", groups["libGLESv2.so"]),
            # libhwui needs libGLESv1_CM before libGLESv2, so shared entry
            # points (glGetString) bind there first. Its fixed-function-only
            # commands have no host thunk and stay with the real library; the
            # OES extension names an ES 1 app imports are in gles1_oes.c.
            ("libGLESv1_CM.so", "libGLESv2.so", sorted(gles1_commands() & set(groups["libGLESv2.so"]))),
        ):
            real = "re_" + soname[3:]
            stub = staging / real
            subprocess.run(common + ["-fPIC", "-shared", "-Wl,-soname," + real,
                                     "-Wno-unused-command-line-argument",
                                     "-x", "assembler", "/dev/null", "-o", str(stub)],
                           check=True)
            assembly = staging / ("managed-" + soname + ".S")
            hidden = {name for name in exports if name.startswith('ANativeWindow_')} if soname == "libandroid.so" else set()
            if soname == "libEGL.so":
                wrappers = set(re.findall(r"^\s+EGL_WRAPPER\((\w+)\)",
                    (ROOT / "Guest/Android/Adapters/egl.c").read_text(), re.MULTILINE))
                hidden = wrappers.intersection(exports)
            assembly.write_text(shim(table, exports, hidden))
            wrapper = [str(ROOT / "Guest/Android/Adapters/surface.c"), str(bionic / "libc.so")] if hidden else []
            if soname == "libEGL.so":
                wrapper = [str(ROOT / "Guest/Android/Adapters/egl.c"), str(bionic / "libc.so"),
                           str(bionic / "libdl.so")]
            if soname == "libGLESv1_CM.so":
                # The OES names of ES 1 apps forward to libGLESv2's functions (built just before, above). The
                # fixed-function commands only an ES 1 context can run get stubs that say so on the first call.
                fixed = staging / "gles1_fixed_function.c"
                fixed.write_text(gles1_fixed_function_stubs(gles1_commands() - set(groups["libGLESv2.so"])))
                wrapper = [str(ROOT / "Guest/Android/Adapters/gles1_oes.c"), str(fixed), str(managed / "libGLESv2.so"),
                           str(bionic / "libc.so")]
            if soname == "libandroid.so":
                wrapper += [str(ROOT / "Guest/Android/Adapters/managed_looper.c"),
                            str(bionic / "libdl.so"), str(bionic / "libdl_android.so")]
                forwards = staging / "managed-libandroid-platform.S"
                forwards.write_text(shim("re_android.so", platform_forwards(staging, exports),
                                         resolver="bifrost_platform_symbol"))
                wrapper.append(str(forwards))
            subprocess.run(common + ["-fPIC", "-shared", "-Wl,-soname," + soname,
                                     "-Wl,--no-as-needed", str(assembly), *wrapper, str(stub),
                                     "-o", str(managed / soname)], check=True)
            names.append("managed/" + soname)
        metadata = {
            "schema_version": 1,
            "runtime_archive_sha256": module.SHA256,
            "dependencies": dependencies,
            "files": {
                name: hashlib.sha256((staging / name).read_bytes()).hexdigest()
                for name in names
            },
        }
        (output / "managed").mkdir(exist_ok=True)
        for name in names:
            (staging / name).replace(output / name)
        manifest = staging / "adapters.json"
        manifest.write_text(json.dumps(metadata, indent=2) + "\n")
        manifest.replace(output / "adapters.json")
    print(output)


