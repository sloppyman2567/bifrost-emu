#!/usr/bin/env python3
"""glcoverage.py — auto-generate missing core GL (<=3.3) rows for
thunk_dp.txt from the vendored Khronos gl.xml.

Candidate selection (deliberately conservative):
  IN  — commands in gl feature blocks api='gl', number<=3.3, not already
        present in the spec (any GL/GLES row counts as present).
  OUT — functions taking GLdouble/GLclampd BY VALUE ('f' is binary32
        only; doubles need a dedicated arg kind — future work).
  OUT — bulk-buffer pixel paths (COMPSIZE referencing width/height/
        depth or uncomputable): they need real SizeKind policies,
        a 64 KiB default bounce would truncate/overread.
  ARGS— '*' param -> 'p', else 'i'.

The generated block is appended INSIDE marked BEGIN/END comments in the
spec itself (the spec stays the single source of truth;
`make opgen-thunk-check` pins the generated header). --check mode
verifies the marked section byte-matches a fresh generation.
"""
import sys
import os
import xml.etree.ElementTree as ET

SPEC_DEFAULT = 'Tools/CodeGen/thunk_dp.txt'
XML_DEFAULT = 'ThirdParty/GLRegistry/gl.xml'
MAX_GL_VERSION = 3.3

# Special-case bulk-pixel functions: exact SizeKind specs.
SPECIAL_SIZES = {
    # name: (args, size_kind)
    'glDrawPixels':         ('iiiiz',      'DRAWPIXELS'),
    'glBitmap':             ('iiffffz',    'BITMAP'),
    'glTexImage1D':         ('iiiiiiiz',   'TEXIMAGE1D'),
    'glTexSubImage1D':      ('iiiiiiz',    'TEXSUBIMAGE1D'),
    'glTexSubImage3D':      ('iiiiiiiiiiz','TEXSUBIMAGE3D'),
    'glPolygonStipple':     ('z',          'STIPPLE'),
    'glGetPolygonStipple':  ('z',          'STIPPLE'),
}

BEGIN_MARK = '# ==== BEGIN AUTOGENERATED CORE GL <=3.3 (Tools/CodeGen/glcoverage.py) ===='
END_MARK = '# ==== END AUTOGENERATED CORE GL ===='
EXT_BEGIN = '# ==== BEGIN AUTOGENERATED EXTENSIONS (Tools/CodeGen/glcoverage.py) ===='
EXT_END = '# ==== END AUTOGENERATED EXTENSIONS ===='
EXT_HEADER_DEFAULT = 'Include/Generated/GLExtensions.hpp'
# Vendor suffixes of promoted entry points: glFooEXT with glFoo's exact
# parameter and return types is the promoted command (OpenGL ES registry
# omits many alias attributes).
VENDOR_SUFFIXES = ('EXT', 'OES', 'KHR', 'ARB', 'NV', 'AMD', 'APPLE', 'ANGLE',
                   'INTEL', 'MESA', 'QCOM', 'IMG', 'ARM', 'OVR')


def load_spec_names(spec_path):
    """name -> set of families; autogenerated block excluded so
    regeneration re-derives rows purely from gl.xml."""
    names = {}
    in_auto = False
    with open(spec_path) as fh:
        for line in fh:
            if line.startswith('# ==== BEGIN AUTOGENERATED'):
                in_auto = True
                continue
            if line.startswith('# ==== END AUTOGENERATED'):
                in_auto = False
                continue
            if in_auto:
                continue
            line = line.split('#', 1)[0].split()
            if len(line) >= 5 and line[1] in ('GL', 'GLES'):
                names.setdefault(line[0], set()).add(line[1])
    return names


def load_registry(xml_path, api='gl', max_ver=MAX_GL_VERSION):
    """-> ({core command names}, {name: Element})."""
    root = ET.parse(xml_path).getroot()
    core = {}
    for f in root.findall('feature'):
        if f.get('api') != api:
            continue
        try:
            num = float(f.get('number'))
        except ValueError:
            continue
        if num > max_ver:
            continue
        for req in f.findall('require'):
            for e in req.findall('command'):
                core[e.get('name')] = True
    cmds = {}
    for c in root.iter('command'):
        pr = c.find('proto')
        nm = pr.find('name') if pr is not None else None
        if nm is not None and nm.text:
            cmds[nm.text] = c
    return core, cmds


def classify(name, cmd):
    """-> (args, size_kind | '-', skip_reason | None)."""
    ps = cmd.findall('param')
    txts = [''.join(p.itertext()) for p in ps]
    # By-value GLdouble/GLclampd params use the native 'd' kind — EXCEPT
    # when mixed with integer scalars (the THUNK_DOUBLE path is
    # double-only; no mixed i+d ABI support).
    has_byval_d = False
    has_int_scalar = False
    chars = []
    for p, tx in zip(ps, txts):
        if '*' in tx:
            chars.append('p')
        elif 'GLdouble' in tx or 'GLclampd' in tx:
            chars.append('d')
            has_byval_d = True
        else:
            chars.append('i')
            has_int_scalar = True
    if has_byval_d and has_int_scalar:
        return None, '-', 'mixed int+double by value'
    lens = [p.get('len') or '' for p, t in zip(ps, txts)
            if '*' in t]
    if any(('width' in l or 'height' in l or 'depth' in l or l == 'COMPSIZE()')
           for l in lens):
        # The seven bulk-pixel paths have hand-derived SizeKinds — emit
        # them with the exact size spec instead of skipping.
        if name in SPECIAL_SIZES:
            a, sz = SPECIAL_SIZES[name]
            return a, sz, None
        return None, '-', 'bulk pixel buffer needs SizeKind'
    args = ''.join(chars)
    return (args if args else '-'), '-', None


PASSES = [
    # (api, version cap, family column)
    ('gl', MAX_GL_VERSION, 'GL'),
    ('gles2', 3.2, 'GLES'),
]


def generate(xml_path, spec_path):
    """-> ({family: rows}, [(name, reason)])."""
    have = load_spec_names(spec_path)
    all_rows = {}
    skipped = []
    for api, max_ver, fam in PASSES:
        core, cmds = load_registry(xml_path, api, max_ver)
        rows = []
        for name in sorted(core):
            if fam in have.get(name, ()):
                continue
            if name not in cmds:
                skipped.append((name, 'referenced but not defined'))
                continue
            args, szkind, why = classify(name, cmds[name])
            if args is None:
                skipped.append((name, why))
                continue
            rows.append('%-26s %-6s %-13s %-5s %-14s %-6s'
                        % (name, fam, args, '-', '-', szkind))
        all_rows[fam] = rows
    return all_rows, skipped


def row_columns(toks):
    """(args, ret, policy, size, flag) as thunkgen.parse_rows reads them."""
    flag = ''
    if toks[-1] == 'SYNC':
        flag, toks = 'SYNC', toks[:-1]
    return (''.join(toks[2:-3]), toks[-3], toks[-2], toks[-1], flag)


def load_spec_rows(spec_path):
    """name -> {family: row_columns} outside every autogenerated block."""
    rows = {}
    in_auto = False
    with open(spec_path) as fh:
        for line in fh:
            if line.startswith('# ==== BEGIN AUTOGENERATED'):
                in_auto = True
                continue
            if line.startswith('# ==== END AUTOGENERATED'):
                in_auto = False
                continue
            toks = line.split('#', 1)[0].split()
            if in_auto or len(toks) < 6 or toks[1] not in ('GL', 'GLES'):
                continue
            rows.setdefault(toks[0], {})[toks[1]] = row_columns(toks)
    return rows


def signature(cmd):
    """Return and parameter types without names, for promotion checks."""
    def typed(elem):
        text = ''.join(elem.itertext())
        name = elem.find('name').text
        return ' '.join(text[:text.rfind(name)].split())
    return (typed(cmd.find('proto')),
            tuple(typed(p) for p in cmd.findall('param')))


def extension_safety(name, cmd):
    """-> args for a generic row, or (None, reason). Generic rows bounce
    pointers like the core rows; anything else hides its extension."""
    proto = ''.join(cmd.find('proto').itertext())
    if '*' in proto[:proto.rfind(name)]:
        return None, 'returns a host pointer'
    for p in cmd.findall('param'):
        text = ''.join(p.itertext())
        ptype = p.find('ptype')
        if '**' in text:
            return None, 'nested pointer array'
        if '*' in text and 'void' in text:
            return None, 'untyped data buffer'
        if (ptype is not None and 'PROC' in ptype.text) or 'PROC' in text:
            return None, 'callback'
        if p.find('name').text in ('fd', 'handle') or 'handle' in p.find('name').text.lower():
            return None, 'host fd or handle'
    args, size, why = classify(name, cmd)
    if args is None or size != '-':
        return None, why or 'sized buffer'
    if 'f' in args and args.rstrip('f').count('f'):
        return None, 'float before integer argument (unsupported mixed ABI)'
    return args, None


def generate_extensions(xml_path, spec_path, core_rows):
    """-> ({family: rows}, {family: sorted hidden extension names})."""
    rows = load_spec_rows(spec_path)
    for fam, lines in core_rows.items():
        for line in lines:
            toks = line.split()
            rows.setdefault(toks[0], {})[fam] = row_columns(toks)
    root = ET.parse(xml_path).getroot()
    cmds = {c.find('proto').find('name').text: c
            for c in root.find('commands').iter('command')}
    out, hidden = {}, {}
    for api, _, fam in PASSES:
        planned = {}
        hidden[fam] = []

        def resolve(name):
            if fam in rows.get(name, {}) or name in planned:
                return True
            if name.endswith('ARB') and name[:-3] in rows:
                return True  # GetProcAddress strips ARB (Dispatch.cpp)
            if name in rows:  # hand row in the other family
                planned[name] = next(iter(rows[name].values()))
                return True
            cmd = cmds.get(name)
            if cmd is None:
                return False
            targets = []
            alias = cmd.find('alias')
            if alias is not None:
                targets.append(alias.get('name'))
            for suffix in VENDOR_SUFFIXES:
                core = name[:-len(suffix)]
                if name.endswith(suffix) and core in cmds and \
                        signature(cmds[core]) == signature(cmd):
                    targets.append(core)
            for target in targets:
                families = rows.get(target, {})
                cols = families.get(fam) or next(iter(families.values()), None)
                if cols:
                    planned[name] = cols
                    return True
            args, _ = extension_safety(name, cmd)
            if args is None:
                return False
            planned[name] = (args, '-', '-', '-', '')
            return True

        for ext in root.find('extensions'):
            if api not in (ext.get('supported') or '').split('|'):
                continue
            need = [c.get('name') for req in ext.findall('require')
                    if req.get('api') in (None, api) for c in req.findall('command')]
            if not all([resolve(n) for n in need]):
                hidden[fam].append(ext.get('name'))
        out[fam] = [('%-26s %-6s %-13s %-5s %-14s %-6s %s' % (n, fam, a or '-', r, p, s, f)).rstrip()
                    for n, (a, r, p, s, f) in sorted(planned.items())]
        hidden[fam].sort()
    return out, hidden


def extensions_header(hidden):
    # Desktop GL keeps its full list: hiding staples such as
    # GL_ARB_multitexture for one unthunkable variant would stop working
    # desktop games. Only OpenGL ES (Android guests) is filtered.
    lines = ['// GLExtensions.hpp — GENERATED by Tools/CodeGen/glcoverage.py. DO NOT EDIT.',
             '//',
             '// OpenGL ES extensions with a command that cannot be thunked (host fds,',
             '// untyped data buffers, callbacks, nested arrays). GraphicThunk removes',
             '// them from guest-visible ES extension queries; every other registry ES',
             '// extension has a row for each command. Sorted for binary search.',
             '#pragma once', '', 'namespace arm64emu::thunk {', '',
             'inline constexpr const char* kHiddenGlesExtensions[] = {']
    lines += ['    "%s",' % n for n in hidden['GLES']]
    lines += ['};', '', '}  // namespace arm64emu::thunk', '']
    return '\n'.join(lines)


def main():
    pos = [a for a in sys.argv[1:] if not a.startswith('--')]
    check_only = '--check' in sys.argv[1:]
    spec_path = pos[0] if len(pos) > 0 else SPEC_DEFAULT
    xml_path = pos[1] if len(pos) > 1 else XML_DEFAULT

    header_path = EXT_HEADER_DEFAULT
    all_rows, skipped = generate(xml_path, spec_path)
    ext_rows, hidden = generate_extensions(xml_path, spec_path, all_rows)
    total = sum(len(v) for v in all_rows.values())
    ext_total = sum(len(v) for v in ext_rows.values())

    def blocks_text():
        out = []
        for _, _, fam in PASSES:
            mk_b = BEGIN_MARK.replace('CORE GL <=3.3',
                                      'CORE %s' % ('GL <=3.3' if fam == 'GL'
                                                   else 'GLES <=3.2'))
            mk_e = END_MARK.replace('CORE GL', 'CORE %s' % fam)
            out.append('\n'.join([mk_b] + all_rows[fam] + [mk_e]))
        out.append('\n'.join(
            [EXT_BEGIN,
             '# Registry aliases and promoted entry points copy the core row;',
             '# other commands use generic rows. Extensions with a command that',
             '# cannot be thunked are listed in ' + EXT_HEADER_DEFAULT + '.']
            + ext_rows['GLES'] + ext_rows['GL'] + [EXT_END]))
        return '\n\n'.join(out)

    with open(spec_path) as fh:
        cur = fh.read()
    first_b = BEGIN_MARK.replace('CORE GL <=3.3', 'CORE GL <=3.3')
    last_e = EXT_END if EXT_END in cur else END_MARK.replace('CORE GL', 'CORE GLES')

    if first_b in cur and last_e in cur:
        pre = cur[:cur.index(first_b)]
        post = cur[cur.index(last_e) + len(last_e):]
        old_block = cur[cur.index(first_b):
                        cur.index(last_e) + len(last_e)]
    else:
        pre = cur.rstrip('\n') + '\n\n'
        post = ''
        old_block = None

    new_block = blocks_text()
    new_header = extensions_header(hidden)

    if check_only:
        if old_block is None:
            print("glcoverage: no autogenerated block found in", spec_path)
            return 2
        if old_block != new_block:
            import difflib
            diff = list(difflib.unified_diff(
                old_block.splitlines(), new_block.splitlines(),
                'spec', 'regenerated', lineterm=''))
            print('\n'.join(diff[:60]))
            print("glcoverage: autogenerated block DRIFTED")
            return 2
        old_header = open(header_path).read() if os.path.exists(header_path) else None
        if old_header != new_header:
            print("glcoverage: %s DRIFTED" % header_path)
            return 2
        print("glcoverage: autogenerated blocks up to date (%d core, %d extension rows; "
              "%d GLES / %d GL extensions hidden)"
              % (total, ext_total, len(hidden['GLES']), len(hidden['GL'])))
        return 0

    with open(spec_path, 'w') as fh:
        fh.write(pre + new_block + post)
    with open(header_path, 'w') as fh:
        fh.write(new_header)
    print("glcoverage: wrote %d core and %d extension rows; hid %d GLES / %d GL extensions"
          % (total, ext_total, len(hidden['GLES']), len(hidden['GL'])))
    for name, why in skipped:
        print("  SKIP %-32s (%s)" % (name, why))
    return 0


if __name__ == '__main__':
    sys.exit(main())
