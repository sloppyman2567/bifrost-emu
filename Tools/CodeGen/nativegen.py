#!/usr/bin/env python3
"""nativegen.py — generate FrostJIT's native SIMD helper table and its test.

Single source of truth for which AArch64 encodings run through a specialized
native helper (Source/FrostJIT/CodeGen/Native/NativeSIMD.cpp). The classifier
used to be a hand-written mask chain beside the helper bodies, and each helper
batch carried a hand-written encoding list in its test. Both now come from one
spec, so a classified encoding is always tested.

Usage:
    python3 Tools/CodeGen/nativegen.py [--check] SPEC EXPECTED HEADER TEST

SPEC rows (whitespace separated, '#' comments):
    NAME  KIND  MASK  MATCH  PINS  [GUARD...]
see Tools/CodeGen/native_simd.txt for the fields.

Outputs:
  HEADER  NativeSimdKind, BIFROST_NATIVE_SIMD_KINDS(X) and
          classify_native_simd() for the translator, fallback prediction and
          helper dispatch.
  TEST    a guest fixture that runs every enumerated candidate the classifier
          accepts (as `insn; ret` stubs in .text) over special FP/integer
          inputs with FPCR.DN clear and set, hashing v2. EXPECTED holds the
          per-encoding hashes recorded under QEMU (`make nativegen-expect`);
          the fixture's `gen` argument prints them. A candidate QEMU rejects
          with SIGILL is recorded as hash 0, so classifying an unallocated
          encoding as native fails the test.
"""
import os
import sys

PIN_FIELDS = {"d": (0, 2), "n": (5, 0), "m": (16, 1)}  # shift, register
MAX_FREE_BITS = 12

HEADER = r"""// NativeSimdTable.hpp — GENERATED. DO NOT EDIT.
//
// Generated by Tools/CodeGen/nativegen.py from Tools/CodeGen/native_simd.txt.
// To add or change a native SIMD helper encoding, edit the spec and run
// `make nativegen` (and `make nativegen-expect` for the QEMU hashes).
#pragma once
#include <cstdint>

namespace arm64emu {

// One run<KIND> helper body per kind in NativeSIMD.cpp.
#define BIFROST_NATIVE_SIMD_KINDS(X) \
{KINDS_MACRO}

enum class NativeSimdKind : uint8_t {
    None,
#define BIFROST_NATIVE_SIMD_ENUM(kind) kind,
    BIFROST_NATIVE_SIMD_KINDS(BIFROST_NATIVE_SIMD_ENUM)
#undef BIFROST_NATIVE_SIMD_ENUM
};

inline NativeSimdKind classify_native_simd(uint32_t w) {
    using K = NativeSimdKind;
{LOCALS}
{BODY}
    return K::None;
}

} // namespace arm64emu
"""

LOCALS = """    const unsigned sz = (w >> 22) & 3u, q = (w >> 30) & 1u, u = (w >> 29) & 1u;
    const unsigned imm5 = (w >> 16) & 31u, h = (w >> 19) & 15u;
    const bool fp_lanes = !((w >> 22) & 1u) || q;
    const bool across_size = sz < 2 || (sz == 2 && q);
    (void)sz; (void)q; (void)u; (void)imm5; (void)h; (void)fp_lanes; (void)across_size;"""

TEST = r"""/*
 * jit_native_simd_gen.c — GENERATED. DO NOT EDIT.
 *
 * Generated by Tools/CodeGen/nativegen.py from Tools/CodeGen/native_simd.txt:
 * every enumerated encoding FrostJIT classifies as a native SIMD helper runs
 * over special inputs with FPCR.DN clear and set; v2 is hashed per encoding
 * and compared with hashes recorded under QEMU (`make nativegen-expect`,
 * which runs this fixture's `gen` mode). Hash 0 means QEMU raised SIGILL.
 */
#include <setjmp.h>
#include <signal.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

/* Same classifier as Include/Generated/NativeSimdTable.hpp (0 = not native). */
static unsigned native_kind(uint32_t w) {
{LOCALS}
{C_BODY}
    return 0;
}

#define CANDIDATES {COUNT}
/* Candidate i is `.inst word; ret` at native_stubs + 8 * i. */
extern const uint32_t native_stubs[];
__asm__(".text\n.p2align 3\n.globl native_stubs\nnative_stubs:\n"
{STUBS});

static const uint32_t expected[] = {
{EXPECTED}
};

typedef struct { uint8_t b[16]; } V;
static const uint32_t f32s[] = {
    0x00000000, 0x80000000, 0x3fc00000, 0x40200000, 0xc0200000, 0x3f000000,
    0x7f800000, 0xff800000, 0x7fc00001, 0x7f800001, 0xffc00002, 0x7f7fffff,
    0x00000001, 0x501502f9, 0x4b000001, 0xcb7fffff,
};
static const uint64_t f64s[] = {
    0, 0x8000000000000000ull, 0x3ff8000000000000ull, 0xc004000000000000ull,
    0x3fe0000000000000ull, 0x7ff0000000000000ull, 0xfff0000000000000ull,
    0x7ff8000000000001ull, 0x7ff0000000000001ull, 0xfff8000000000002ull,
    0x7fefffffffffffffull, 0x0000000000000001ull, 0x4330000000000001ull,
    0x433fffffffffffffull, 0xc3e0000000000000ull, 0x43e0000000000000ull,
};
static const uint16_t f16s[] = {
    0x0000, 0x8000, 0x3c00, 0x3e00, 0xc100, 0x7c00, 0xfc00, 0x7e01, 0x7c01,
    0xfe02, 0x7bff, 0x0001, 0x83ff, 0x0400, 0x3555, 0xd2a3,
};
/* Input k: bytes, halves, singles or doubles drawn from the special pools. */
static void fill(V* v, unsigned k) {
    for (unsigned lane = 0; lane < 16; ++lane) {
        const unsigned sel = k * 7 + lane * (k % 5 + 1) + k / 3;
        switch (k % 4) {
            case 0: v->b[lane] = (uint8_t)(sel * 37 + k * 11 + (k & 1 ? 0x80 : 0)); break;
            case 1: if (lane < 8) memcpy(v->b + 2 * lane, &f16s[sel % 16], 2); break;
            case 2: if (lane < 4) memcpy(v->b + 4 * lane, &f32s[sel % 16], 4); break;
            default: if (lane < 2) memcpy(v->b + 8 * lane, &f64s[sel % 16], 8); break;
        }
    }
}
static sigjmp_buf trap;
static void on_sigill(int sig) { (void)sig; siglongjmp(trap, 1); }
static void set_fpcr(uint64_t value) { __asm__ volatile("msr fpcr, %0" :: "r"(value)); }

/* Hash of v2 for every input, or 0 when the encoding raised SIGILL. */
static uint32_t run(const uint32_t* stub) {
    uint32_t h = 2166136261u;
    for (unsigned dn = 0; dn < 2; ++dn) {
        set_fpcr(dn ? 1u << 25 : 0);
        for (unsigned k = 0; k < 64; ++k) {
            V n, m, d, out;
            fill(&n, k); fill(&m, k + 17);
            for (int i = 0; i < 16; ++i) d.b[i] = (uint8_t)(0xa5 ^ (i * 29 + k));
            if (sigsetjmp(trap, 1)) { set_fpcr(0); return 0; }
            __asm__ volatile("ldr q0, [%1]\n ldr q1, [%2]\n ldr q2, [%3]\n ldr x0, [%1]\n"
                             "blr %4\n str q2, [%0]"
                             :: "r"(&out), "r"(&n), "r"(&m), "r"(&d), "r"(stub)
                             : "v0", "v1", "v2", "x0", "x30", "memory");
            for (int i = 0; i < 16; ++i) h = (h ^ out.b[i]) * 16777619u;
        }
    }
    set_fpcr(0);
    return h ? h : 1;
}

int main(int argc, char** argv) {
    const int gen = argc > 1 && !strcmp(argv[1], "gen");
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_handler = on_sigill;
    sigaction(SIGILL, &sa, 0);
    unsigned ran = 0, fails = 0;
    if (!gen && sizeof(expected) / sizeof(expected[0]) != 2 * CANDIDATES) {
        printf("jit_native_simd_gen: expectations are stale; run make nativegen-expect\n");
        return 1;
    }
    for (unsigned i = 0; i < CANDIDATES; ++i) {
        const uint32_t* stub = native_stubs + 2 * i;
        const uint32_t word = stub[0];
        if (!native_kind(word)) continue;
        const uint32_t hash = run(stub);
        ++ran;
        if (gen) { printf("0x%08x 0x%08x\n", word, hash); continue; }
        if (expected[2 * i] != word || expected[2 * i + 1] != hash) {
            printf("FAIL %08x hash=%08x want=%08x%s\n", word, hash, expected[2 * i + 1],
                   expected[2 * i] != word ? " (no QEMU expectation; run make nativegen-expect)"
                   : expected[2 * i + 1] ? "" : " (QEMU: SIGILL)");
            ++fails;
        }
    }
    if (gen) return 0;
    if (fails) { printf("jit_native_simd_gen: %u of %u encodings FAILED\n", fails, ran); return 1; }
    printf("jit_native_simd_gen: %u encodings passed\n", ran);
    return 0;
}
"""


def die(msg):
    print("nativegen: " + msg, file=sys.stderr)
    raise SystemExit(2)


def parse_rows(path):
    rows = []
    with open(path) as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            toks = line.split()
            if len(toks) < 5:
                die("%s:%d: need NAME KIND MASK MATCH PINS [GUARD]" % (path, lineno))
            name, kind, mask, match, pins = toks[:5]
            mask, match = int(mask, 16), int(match, 16)
            if match & ~mask:
                die("%s:%d: MATCH has bits outside MASK" % (path, lineno))
            guard = ' '.join(toks[5:]).strip()
            pins = [] if pins == '-' else pins.split(',')
            for p in pins:
                if p not in PIN_FIELDS:
                    die("%s:%d: unknown pin %r" % (path, lineno, p))
            rows.append((name, kind, mask, match, pins, None if guard in ('', '-') else guard))
    return rows


def condition(mask, match, guard):
    cond = "(w & 0x%08XU) == 0x%08XU" % (mask, match)
    return cond + " && (%s)" % guard if guard else cond


def candidates(rows):
    seen, out = set(), []
    for name, kind, mask, match, pins, guard in rows:
        pinned_bits = pinned_value = 0
        for p in pins:
            shift, reg = PIN_FIELDS[p]
            pinned_bits |= 31 << shift
            pinned_value |= reg << shift
        free = [b for b in range(32) if not (mask | pinned_bits) >> b & 1]
        if len(free) > MAX_FREE_BITS:
            die("%s enumerates %d free bits; pin registers or fold guard bits into MASK"
                % (name, len(free)))
        for combo in range(1 << len(free)):
            word = match | pinned_value
            for i, bit in enumerate(free):
                if combo >> i & 1:
                    word |= 1 << bit
            if word not in seen:
                seen.add(word)
                out.append(word)
    return out


def read_expected(path):
    try:
        pairs = [line.split() for line in open(path) if line.strip()]
    except IOError:
        return None
    table = {int(w, 16): int(h, 16) for w, h in pairs}
    return table


def render(rows, expected_path):
    kinds = []
    for r in rows:
        if r[1] not in kinds:
            kinds.append(r[1])
    macro = " \\\n".join("    X(%s)" % k for k in kinds)
    body = "\n".join("    if (%s) return K::%s;  // %s" % (condition(m, mt, g), k, n)
                     for n, k, m, mt, _, g in rows)
    header = (HEADER.replace("{KINDS_MACRO}", macro).replace("{LOCALS}", LOCALS)
              .replace("{BODY}", body))

    c_body = "\n".join("    if (%s) return %d;  /* %s */" % (condition(m, mt, g), kinds.index(k) + 1, n)
                       for n, k, m, mt, _, g in rows)
    words = candidates(rows)
    stubs = "\n".join('    ".inst 0x%08x\\nret\\n"' % w for w in words)
    table = read_expected(expected_path)
    if table is not None:
        # Candidates the classifier rejects run nothing; their slots hold 0, 0.
        exp = ",\n".join("    0x%08x, 0x%08x" % ((w, table[w]) if w in table else (0, 0)) for w in words)
    else:
        exp = "    0"
    test = (TEST.replace("{LOCALS}", LOCALS).replace("{C_BODY}", c_body)
            .replace("{COUNT}", str(len(words))).replace("{STUBS}", stubs)
            .replace("{EXPECTED}", exp))
    return header, test, len(words)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv[1:]
    if len(args) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    spec, expected, header_path, test_path = args
    header, test, count = render(parse_rows(spec), expected)
    outputs = ((header_path, header), (test_path, test))
    if check:
        stale = [p for p, text in outputs if not os.path.exists(p) or open(p).read() != text]
        if stale:
            print("nativegen: %s OUT OF DATE — run `make nativegen`" % ", ".join(stale),
                  file=sys.stderr)
            return 1
        print("nativegen: outputs up to date (%d candidates)" % count)
        return 0
    for path, text in outputs:
        with open(path, "w") as fh:
            fh.write(text)
    print("wrote %s and %s (%d candidates)" % (header_path, test_path, count))
    return 0


if __name__ == "__main__":
    sys.exit(main())
