#!/usr/bin/env python3
"""Generate Include/Generated/OverlayFont.hpp: glyph outlines for the in-window stats panel.

    python3 Tools/CodeGen/overlayfont.py Roboto-Medium.ttf Include/Generated/OverlayFont.hpp

The font is Roboto Medium 2.138 (Apache-2.0, https://github.com/googlefonts/roboto, release asset
roboto-unhinted.zip, SHA-256 of Roboto-Medium.ttf b398bb9c791ddb08f1063d9c874f98e8aadb99132043b2d272a9276cf90c465a).
Only the outlines of printable ASCII, the degree sign, the middle dot and the ellipsis are kept, as
straight lines and quadratic curves in font units, so the panel rasterizes them at any size and needs no
font file at run time. The output is not part of `make generated-check`: that check has no font to read.
"""
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

CODES = list(range(0x20, 0x7F)) + [0xB0, 0xB7, 0x2026]
MOVE, LINE, QUAD, CLOSE = 0, 1, 2, 3


class Outline(BasePen):
    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.ops = []

    def _moveTo(self, p):
        self.ops += [MOVE, *map(round, p)]

    def _lineTo(self, p):
        self.ops += [LINE, *map(round, p)]

    def _qCurveToOne(self, c, p):
        self.ops += [QUAD, *map(round, c), *map(round, p)]

    def _curveToOne(self, a, b, p):
        raise SystemExit("cubic curve: the font is not TrueType")

    def _closePath(self):
        self.ops.append(CLOSE)

    def _endPath(self):
        self.ops.append(CLOSE)


def main(font_path, out_path):
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    upem = font["head"].unitsPerEm
    os2 = font["OS/2"]
    stream, glyphs = [], []
    for code in CODES:
        name = cmap[code]
        pen = Outline(glyph_set)
        glyph_set[name].draw(pen)
        if any(abs(v) > 32767 for v in pen.ops):
            raise SystemExit(f"{name}: coordinate out of int16 range")
        glyphs.append((code, len(stream), len(pen.ops), glyph_set[name].width))
        stream += pen.ops
    lines = [
        "// Generated by Tools/CodeGen/overlayfont.py from Roboto Medium 2.138 (Apache-2.0, see LICENSES/README.md). Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "namespace arm64emu::window_stats::overlay_font {",
        f"constexpr int kUnitsPerEm = {upem};",
        f"constexpr int kCapHeight = {os2.sCapHeight};",
        f"constexpr int kXHeight = {os2.sxHeight};",
        "// Outline ops in font units, y up: MOVE x y, LINE x y, QUAD cx cy x y, CLOSE.",
        "enum Op : int16_t { MOVE, LINE, QUAD, CLOSE };",
        "struct Glyph {",
        "  uint32_t code;",
        "  uint32_t first;  // index into kOutline",
        "  uint32_t count;",
        "  int32_t advance;",
        "};",
        f"constexpr Glyph kGlyphs[{len(glyphs)}] = {{",
    ]
    for code, first, count, advance in glyphs:
        lines.append(f"    {{0x{code:X}, {first}, {count}, {advance}}},")
    lines.append("};")
    lines.append(f"constexpr int16_t kOutline[{len(stream)}] = {{")
    row = []
    for value in stream:
        row.append(str(value))
        if len(row) == 24:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    lines.append("}  // namespace arm64emu::window_stats::overlay_font")
    with open(out_path, "w") as out:
        out.write("\n".join(lines) + "\n")
    print(f"{len(glyphs)} glyphs, {len(stream)} outline values -> {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
