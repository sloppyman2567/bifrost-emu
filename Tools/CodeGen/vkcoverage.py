#!/usr/bin/env python3
"""vkcoverage.py — generate the core Vulkan rows thunk_dp.txt is missing,
from the vendored Khronos vk.xml registry.

Candidates are the commands required by <feature api="vulkan"> blocks that
have no VK row yet. Each is classified mechanically:

  DEEP  — the command has a generated deep-marshal plan (vkmarshalgen.py's
          CMD_PLANS / CMD_CREATE_PLANS / CMD_NULLIFY_PLANS), so its nested
          guest pointers are staged for the host call. Policy
          VK_CMD_DEEP_OUT when a pointer is writable (the host writes
          through it), VK_CMD_DEEP otherwise.
  PLAIN — every pointer parameter addresses a scalar, a handle, a string,
          or a struct with no pointer members at all (recursively, function
          pointers included): generic guest→host translation is exact.
          Policy VULKAN.
  SKIP  — everything else, with the reason printed. These need a hand arm
          (OUT struct writeback, template-defined payloads, uncounted
          void*, fixed C arrays passed by value).

A DEEP row whose command has no plan in Include/Generated/VulkanMarshal.hpp
is a hard error in vkxmlcheck.py — the generator never emits one.

The generated block is appended INSIDE marked BEGIN/END comments in the spec
itself (the spec stays the single source of truth; `make opgen-thunk-check`
pins the generated header). --check verifies the marked section byte-matches
a fresh generation.

Usage: python3 Tools/CodeGen/vkcoverage.py [spec] [vk.xml]
       python3 Tools/CodeGen/vkcoverage.py --check [spec] [vk.xml]
"""
import sys
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vkxml import parse_registry, arg_kinds, layout_all
import vkmarshalgen as vm

SPEC_DEFAULT = 'Tools/CodeGen/thunk_dp.txt'
XML_DEFAULT = 'ThirdParty/VulkanHeaders/registry/vk.xml'

BEGIN_MARK = ('# ==== BEGIN AUTOGENERATED CORE VULKAN '
              '(Tools/CodeGen/vkcoverage.py) ====')
END_MARK = '# ==== END AUTOGENERATED CORE VULKAN ===='

# Every command the deep-marshal generator emits a plan for.
DEEP_PLANNED = (set(vm.CMD_PLANS) | set(vm.CMD_CREATE_PLANS) |
                set(vm.CMD_NULLIFY_PLANS) | set(vm.CMD_STRUCT_IO_PLANS))


def load_spec_names(spec_path):
    """Names already carrying a VK row, outside every autogenerated block
    (regeneration re-derives those rows from vk.xml alone)."""
    names = set()
    in_auto = False
    with open(spec_path) as fh:
        for line in fh:
            if line.startswith('# ==== BEGIN AUTOGENERATED'):
                in_auto = True
                continue
            if line.startswith('# ==== END AUTOGENERATED'):
                in_auto = False
                continue
            if in_auto:
                continue
            toks = line.split('#', 1)[0].split()
            if len(toks) >= 6 and toks[1] == 'VK':
                names.add(toks[0])
    return names


def core_commands(xml_path):
    """{name: True} for every command a Vulkan feature block requires."""
    import xml.etree.ElementTree as ET
    root = ET.parse(xml_path).getroot()
    out = {}
    for f in root.findall('feature'):
        api = (f.get('api') or '').split(',')
        if 'vulkan' not in [a.strip() for a in api]:
            continue
        for req in f.findall('require'):
            for c in req.findall('command'):
                out[c.get('name')] = True
    return out


def has_pointer_members(name, reg, cache, depth=0):
    """True when the struct (or anything it embeds by value) holds a
    pointer the host driver would dereference — pNext, arrays, function
    pointers (vk.xml models PFN_ members without a '*')."""
    if name in cache:
        return cache[name]
    if depth > 12:
        return True
    members = reg['structs'].get(name)
    if members is None:
        return True          # unknown layout: assume the worst
    cache[name] = True       # cycle guard
    res = False
    for m in members:
        if m.is_ptr or m.type in reg.get('funcptrs', ()) or \
                m.type.startswith('PFN_'):
            res = True
            break
        if m.type in reg['structs'] and \
                has_pointer_members(m.type, reg, cache, depth + 1):
            res = True
            break
    cache[name] = res
    return res


def plain_safe(cmd, reg, cache):
    """-> None when generic translation is exact for every pointer, else a
    human-readable reason."""
    kinds = arg_kinds(cmd, reg)
    has_ptr = any(p.is_ptr or p.array_len for p in cmd.params)
    for p, k in zip(cmd.params, kinds):
        if not p.is_ptr and not p.array_len:
            if k == 'f' and has_ptr:
                return f'{p.name}: float mixed with pointer args'
            continue
        if p.len_:
            return f'{p.name}: dynamically-sized parameter'
        t = p.type
        if t == 'void':
            if p.const:
                continue      # read-only payload (template data): the host
                              # driver only reads it, translation suffices
            return f'{p.name}: uncounted non-const buffer'
        if t == 'char':
            continue                      # NUL-terminated string
        if t.startswith('PFN_') or t in reg.get('funcptrs', ()):
            return f'{p.name}: function pointer'
        if t in reg['structs'] and has_pointer_members(t, reg, cache):
            return f'{p.name}: {t} carries guest pointers'
    return None


def classify(name, cmd, reg, cache):
    """-> (args, policy) or (None, reason)."""
    chars = []
    for p, k in zip(cmd.params, arg_kinds(cmd, reg)):
        if p.is_ptr or p.array_len:      # array params decay to pointers
            chars.append('p')
        elif k == 'f':
            chars.append('f')
        else:
            chars.append('i')
    # THUNK_MIXED_FP forwards the integer and float registers verbatim and
    # skips pointer translation, so it is only usable when there are no
    # pointers at all and the shapes match Dispatch.cpp (1 int + <=2 fp).
    if 'f' in chars:
        first_f = chars.index('f')
        if any(c != 'f' for c in chars[first_f:]):
            return None, 'float before an integer/pointer argument'
        if first_f > 1 or chars.count('f') > 2:
            return None, 'mixed int+float arity outside Dispatch.cpp arms'
    args = ''.join(chars)
    if name in DEEP_PLANNED:
        writable = any(p.is_ptr and not p.const for p in cmd.params)
        return args, ('VK_CMD_DEEP_OUT' if writable else 'VK_CMD_DEEP')
    why = plain_safe(cmd, reg, cache)
    if why is not None:
        return None, why
    return args, 'VULKAN'


def generate(xml_path, spec_path):
    reg = parse_registry(xml_path)
    have = load_spec_names(spec_path)
    cache = {}
    rows, skipped = [], []
    for name in sorted(core_commands(xml_path)):
        if name in have:
            continue
        cmd = reg['commands'].get(name)
        if cmd is None:
            skipped.append((name, 'referenced but not defined'))
            continue
        args, policy = classify(name, cmd, reg, cache)
        if args is None:
            skipped.append((name, policy))
            continue
        rows.append('%-26s %-6s %-13s %-5s %-14s %-6s'
                    % (name, 'VK', args, '-', policy, '-'))
    return rows, skipped


def block_text(rows, n_planned, n_plain):
    head = [
        BEGIN_MARK,
        '# %d core Vulkan commands: %d deep-marshalled (vk.xml plans), '
        '%d generic-translated.' % (len(rows), n_planned, n_plain),
        '# Commands that need a hand arm are listed by '
        '`python3 Tools/CodeGen/vkcoverage.py`; regenerate with '
        '`make vkcoverage`.',
    ]
    return '\n'.join(head + rows + [END_MARK])


def main():
    pos = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv[1:]
    spec_path = pos[0] if len(pos) > 0 else SPEC_DEFAULT
    xml_path = pos[1] if len(pos) > 1 else XML_DEFAULT

    rows, skipped = generate(xml_path, spec_path)
    n_planned = sum(1 for r in rows if 'VK_CMD_DEEP' in r)
    new_block = block_text(rows, n_planned, len(rows) - n_planned)

    with open(spec_path) as fh:
        cur = fh.read()
    if BEGIN_MARK in cur and END_MARK in cur:
        pre = cur[:cur.index(BEGIN_MARK)]
        post = cur[cur.index(END_MARK) + len(END_MARK):]
        old_block = cur[cur.index(BEGIN_MARK):cur.index(END_MARK) + len(END_MARK)]
    else:
        pre = cur.rstrip('\n') + '\n\n'
        post = ''
        old_block = None

    if check:
        if old_block is None:
            print('vkcoverage: no autogenerated block found in', spec_path)
            return 2
        if old_block != new_block:
            import difflib
            diff = list(difflib.unified_diff(
                old_block.splitlines(), new_block.splitlines(),
                'spec', 'regenerated', lineterm=''))
            print('\n'.join(diff[:60]))
            print('vkcoverage: autogenerated block DRIFTED')
            return 2
        print('vkcoverage: autogenerated block up to date (%d rows: '
              '%d deep, %d generic)' % (len(rows), n_planned,
                                        len(rows) - n_planned))
        return 0

    with open(spec_path, 'w') as fh:
        fh.write(pre + new_block + post)
    print('vkcoverage: wrote %d rows (%d deep, %d generic); %d commands '
          'left for hand arms' % (len(rows), n_planned, len(rows) - n_planned,
                                  len(skipped)))
    for name, why in skipped:
        print('  SKIP %-40s (%s)' % (name, why))
    return 0


if __name__ == '__main__':
    sys.exit(main())
